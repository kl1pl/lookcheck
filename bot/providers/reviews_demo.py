def _reviews(entries: list[str], start: datetime, per_day: int, authors: list[str]) -> list[Review]:
    """Генератор отзывов: к дате старта прибавляем по per_day отзывов в день."""
    out: list[Review] = []
    for i, text in enumerate(entries):
        day_offset = i // per_day
        author = authors[i % len(authors)]
        out.append(
            Review(
                text=text,
                rating=5 if "!" in text or "супер" in text.lower() or "доволен" in text.lower() or "нравится" in text.lower() or "отлично" in text.lower() else (1 if any(
                    k in text.lower() for k in ("брак", "перестал", "не работа", "маломер", "жмут", "впритык", "не соответств")
                ) else 5),
                date=start + timedelta(days=day_offset, hours=i % 10),
                author_id=author,
            )
        )
    return out


